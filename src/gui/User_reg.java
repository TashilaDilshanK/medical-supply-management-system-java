    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String fname = jTextField1.getText();
        String lname = jTextField2.getText();
        String mobile = jTextField5.getText();
        String email = jTextField6.getText();
        String password = jTextField7.getText();
        String gender = jComboBox2.getSelectedItem().toString();
        String utyp = jComboBox3.getSelectedItem().toString();

        if (fname.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter First Name", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (lname.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Last Name", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (mobile.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Contact Number", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (!Pattern.compile("^[a-z0-9._%+-]+@[a-z0-9.-]+\\.[a-z]{2,6}$").matcher(email).matches()) {
            JOptionPane.showMessageDialog(this, "Invalid email address", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Emaile", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (gender.equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please Select Gender", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (utyp.equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please Select Type", "warning", JOptionPane.WARNING_MESSAGE);
        } else {

            try {

                ResultSet rs1 = MySQL.search("SELECT `g_id` FROM `gender` WHERE `gender` = '" + gender + "'");
                rs1.next();

                String gender_id = rs1.getString("g_id");

                ResultSet rs2 = MySQL.search("SELECT `type_id` FROM `user_type` WHERE `user_type` = '" + utyp + "'");
                rs2.next();

                String typ_id = rs2.getString("type_id");

                MySQL.iud("INSERT INTO `msd_db`.`user` (`fname`, `lname`, `mobile`, `email`, `password`, `g_id`, `user_type_id`) VALUES  ('" + fname + "', '" + lname + "', '" + mobile + "', '" + email + "', '" + password + "', '" + Integer.parseInt(gender_id) + "',  '" + Integer.parseInt(typ_id) + "');");

                resetFields();
                //JOptionPane.showMessageDialog(this, "New User Acoount Regidterd", "Success", JOptionPane.INFORMATION_MESSAGE);
                Save s = new Save(this, true);
                s.setVisible(true);

            } catch (Exception e) {
                e.printStackTrace();
            }

        }
    }//GEN-LAST:event_jButton3ActionPerformed

