    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        if (jTextField1.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Plase enter your username or email", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (jPasswordField1.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Place enter your password", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            String username = jTextField1.getText();
            String password = jPasswordField1.getText();

            try {
                ResultSet resultset = MySQL.search("SELECT * from `user` WHERE `email`='" + username + "' AND `password`='" + password + "'");
                if (resultset.next()) {
                    userId = Integer.parseInt(resultset.getString("u_id"));
                    Home home = new Home();
                    home.setVisible(true);
                    this.dispose();

                } else {
                    JOptionPane.showMessageDialog(this, "Invalid username or password", "Warning", JOptionPane.WARNING_MESSAGE);

                    //jTextField1.setText("");
                    jPasswordField1.setText("");

                }
            } catch (Exception e) {
                e.printStackTrace();

            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

