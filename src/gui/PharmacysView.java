    public void loadPha() {
        try {
            ResultSet rs = MySQL.search("SELECT `famecies`.`id`,`famecies`.`fname`,`famecies`.`lname`, `famecies`.`address`,`famecies`.`contact`,`famecies`.`email`, `gender`.`gender` AS `gender`, `hospitel`.`name` AS `hospitel` FROM `famecies` INNER JOIN `gender` ON `famecies`.`gender_id` =`gender`.`g_id` INNER JOIN `hospitel` ON `famecies`.`hospitel_id` =`hospitel`.`id` ORDER BY `famecies`.`id` ASC;");

            
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("id"));
                v.add(rs.getString("fname"));
                v.add(rs.getString("lname"));
                v.add(rs.getString("contact"));
                v.add(rs.getString("address"));
                v.add(rs.getString("email"));
                v.add(rs.getString("gender"));
                v.add(rs.getString("hospitel"));

                dtm.addRow(v);

            }

            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
