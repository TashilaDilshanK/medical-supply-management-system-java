    public void loadStock() {
        try {
            ResultSet rs = MySQL.search("SELECT medicin.medicin,stock.qut FROM stock INNER JOIN medicin ON stock.m_id = medicin.m_id ORDER BY stock.id ASC;");

            DefaultTableModel dtm = (DefaultTableModel) jTable3.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("medicin"));
                v.add(rs.getString("qut"));
                dtm.addRow(v);

            }

            jTable3.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    public void loadStock(String text) {
        try {
            ResultSet rs = MySQL.search("SELECT medicin.medicin,stock.qut FROM stock INNER JOIN medicin ON stock.m_id = medicin.m_id WHERE medicin.medicin LIKE '" + text + "%'  ORDER BY stock.id ASC;");

            DefaultTableModel dtm = (DefaultTableModel) jTable3.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("medicin"));
                v.add(rs.getString("qut"));
                dtm.addRow(v);

            }

            jTable3.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

