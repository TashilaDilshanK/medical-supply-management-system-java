    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:

        Date date = jDateChooser1.getDate();
        String name = jTextField2.getText();
        String mg = jTextField3.getText();
        String qty = jTextField4.getText();
        String hos = jComboBox1.getSelectedItem().toString();

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter The Drug", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (mg.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Milligrams", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (qty.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter The Dosage", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (hos.equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please Select Hospital Name", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (date == null) {
            JOptionPane.showMessageDialog(this, "Please Enter Date", "warning", JOptionPane.WARNING_MESSAGE);
        } else {

            try {

                ResultSet rs2 = MySQL.search("SELECT `id` FROM `hospitel` WHERE `name` = '" + hos + "'");
                rs2.next();

                String hosp_id = rs2.getString("id");

                String date1 = sdf.format(jDateChooser1.getDate());

                MySQL.iud("INSERT INTO `msd_db`.`reqwest_order` (`date`, `name`, `mg`, `qty`, `hospitel_id`) VALUES ('" + date1 + "', '" + name + "', '" + mg + "', '" + qty + "',  '" + Integer.parseInt(hosp_id) + "');");

                //JOptionPane.showMessageDialog(this, "New  Regidterd", "Success", JOptionPane.INFORMATION_MESSAGE);
                comfom com = new comfom(this, true);
                com.setVisible(true);
            } catch (Exception e) {
                e.printStackTrace();
            }

        }
    }//GEN-LAST:event_jButton1ActionPerformed

