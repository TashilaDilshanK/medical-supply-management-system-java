    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:

        String hname = jTextField1.getText();
        String address = jTextField2.getText();
        String distric = jTextField3.getText();
        String director = jTextField4.getText();
        String mobile = jTextField5.getText();
        String email = jTextField6.getText();
        String pharmacy = jComboBox1.getSelectedItem().toString();

        if (hname.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Name", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (address.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Address", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (director.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Director/MS", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (mobile.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Contact Number", "warning", JOptionPane.WARNING_MESSAGE);
        } else if (!Pattern.compile("^[a-z0-9._%+-]+@[a-z0-9.-]+\\.[a-z]{2,6}$").matcher(email).matches()) {
            JOptionPane.showMessageDialog(this, "Invalid email address", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (pharmacy.equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please Select Pharmacys", "warning", JOptionPane.WARNING_MESSAGE);
        } else {

            try {

                ResultSet rs1 = MySQL.search("SELECT `id` FROM `hed_famecies` WHERE `fname` = '" + pharmacy + "'");
                rs1.next();

                String newhph_id = rs1.getString("id");

                MySQL.iud("INSERT INTO `msd_db`.`hospitel` (`name`, `address`, `email`, `contact`, `ms`, `hed_famecies_id`) VALUES ('" + hname + "', '" + address + "', '" + email + "', '" + mobile + "', '" + director + "', '" + newhph_id + "');");

                resetFields();
                //JOptionPane.showMessageDialog(this, "New User Acoount Regidterd", "Success", JOptionPane.INFORMATION_MESSAGE);

                Save s = new Save(this, true);
                s.setVisible(true);

            } catch (Exception e) {
                e.printStackTrace();
            }

        }
    }//GEN-LAST:event_jButton1ActionPerformed

