    public void loadOrder() {
        try {
            ResultSet rs = MySQL.search("SELECT `reqwest_order`.`id`,`reqwest_order`.`date`,`reqwest_order`.`name`,`reqwest_order`.`qty`,`hospitel`.`name` AS `hospitel`FROM `reqwest_order`INNER JOIN `hospitel` ON `reqwest_order`.`hospitel_id` =`hospitel`.`id`ORDER BY `reqwest_order`.`id` ASC;");

            //DefaultTableModel dtm = new DefaultTableModel();
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("id"));
                v.add(rs.getString("date"));
                v.add(rs.getString("name"));
                v.add(rs.getString("qty"));
                v.add(rs.getString("hospitel"));
                dtm.addRow(v);

            }

            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();

        }
    }

