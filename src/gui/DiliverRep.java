    public void loadDiliver() {
        try {
            ResultSet rs = MySQL.search("SELECT suplyi_or.sup_id,suplyi_or.date AS sup_date,suplyi_or.qty,vehical.v_number AS v_id,reqwest_order.id AS id,reqwest_order.qty AS or_qty,batch_number_has_suplyi_or.bn_id,hospitel.name FROM suplyi_or INNER JOIN vehical ON suplyi_or.v_id=vehical.v_id INNER JOIN batch_number_has_suplyi_or ON batch_number_has_suplyi_or.sup_id=suplyi_or.sup_id INNER JOIN reqwest_order ON suplyi_or.order_id = reqwest_order.id INNER JOIN hospitel ON reqwest_order.hospitel_id = hospitel.id ORDER BY suplyi_or.sup_id ASC;");

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("sup_id"));
                v.add(rs.getString("sup_date"));
                v.add(rs.getString("qty"));
                v.add(rs.getString("v_id"));
                v.add(rs.getString("bn_id"));
                v.add(rs.getString("id"));
                v.add(rs.getString("or_qty"));
                v.add(rs.getString("name"));
                dtm.addRow(v);

            }

            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

