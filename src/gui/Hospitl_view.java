    public void loadHos() {
        try {
            ResultSet rs = MySQL.search("SELECT * FROM `hospitel` ORDER BY `hospitel`.`id` ASC");

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("id"));
                v.add(rs.getString("name"));
                v.add(rs.getString("address"));
                v.add(rs.getString("contact"));
                v.add(rs.getString("email"));
                v.add(rs.getString("ms"));
                 v.add(rs.getString("hed_famecies_id"));
                dtm.addRow(v);

            }

            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    public void loadHos(String text) {
        try {
            ResultSet rs = MySQL.search("SELECT * FROM `hospitel` WHERE `hospitel`.`id` LIKE '" + text + "%' OR `hospitel`.`name` LIKE '" + text + "%' OR `hospitel`.`ms` LIKE '" + text + "%' ORDER BY `hospitel`.`id` ASC;");

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("id"));
                v.add(rs.getString("name"));
                v.add(rs.getString("address"));
                v.add(rs.getString("contact"));
                v.add(rs.getString("email"));
                v.add(rs.getString("ms"));
                dtm.addRow(v);

            }

            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

