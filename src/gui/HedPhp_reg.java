    public void loadHeadPha() {
        try {
            ResultSet rs = MySQL.search("SELECT `hed_famecies`.`id`,`hed_famecies`.`fname`,`hed_famecies`.`lname`, `hed_famecies`.`address`,`hed_famecies`.`contact`,`hed_famecies`.`email`, `gender`.`gender` AS `gender` FROM `hed_famecies` INNER JOIN `gender` ON `hed_famecies`.`g_id` =`gender`.`g_id` ORDER BY `hed_famecies`.`id` ASC;");

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("id"));
                v.add(rs.getString("fname"));
                v.add(rs.getString("lname"));
                v.add(rs.getString("contact"));
                v.add(rs.getString("address"));
                v.add(rs.getString("email"));
                v.add(rs.getString("gender"));

                dtm.addRow(v);

            }

            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

